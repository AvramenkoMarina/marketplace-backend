/** TypeORM's pg driver returns UPDATE/INSERT ... RETURNING as [rows, rowCount]. */
export function queryRows<T>(result: unknown): T[] {
  if (
    Array.isArray(result) &&
    result.length === 2 &&
    Array.isArray(result[0]) &&
    typeof result[1] === 'number'
  ) {
    return result[0] as T[];
  }
  return result as T[];
}
